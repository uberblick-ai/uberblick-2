#!/usr/bin/env node
// Copy each drawn format's authoring guide, at the resolved package version,
// into a generated module so bundled builds serve it without reading node_modules.
// Run after changing a format package's catalog version: node scripts/sync-format-guides.mjs
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export const GUIDES = [
  { topic: "ablauf", name: "@uberblick/ablauf", file: "guide.md", repo: "uberblick-ai/ablauf", repoPath: "spike/PRIMER.md" },
  { topic: "wireframe", name: "@uberblick/wireframe", file: "GUIDE.md", repo: "uberblick-ai/wireframe-md", repoPath: "GUIDE.md" },
];

/** The guide text and where it came from, for one format at its installed version. */
export function readGuide({ topic, name, file, repo, repoPath }) {
  // Read the installed copy directly: neither package exports ./package.json.
  const packageDir = join(root, "node_modules", name);
  const { version } = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
  const shipped = join(packageDir, file);
  const standIn = join(root, "format-guides", `${topic}-${version}.md`);
  const fromPackage = existsSync(shipped);
  if (!fromPackage && !existsSync(standIn)) throw new Error(`${name}@${version} ships no ${file} and has no stand-in at ${standIn}`);
  const text = readFileSync(fromPackage ? shipped : standIn, "utf8").trimEnd();
  return {
    topic, name, version, standIn: !fromPackage,
    url: `https://github.com/${repo}/blob/v${version}/${repoPath}`,
    sha256: createHash("sha256").update(text).digest("hex"),
    text,
  };
}

export function render() {
  const guides = GUIDES.map(readGuide);
  return "// Generated by scripts/sync-format-guides.mjs. Do not edit.\n" +
    "/** Authoring guides of the drawn formats, at the versions this workspace resolves. */\n" +
    `export const FORMAT_GUIDES = ${JSON.stringify(Object.fromEntries(guides.map((guide) => [guide.topic, guide])), null, 2)} as const;\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "src", "generated", "format-guides.ts"), render());
}
